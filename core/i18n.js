export const messages = M;
const rules = { en: new Intl.PluralRules("en"), pl: new Intl.PluralRules("pl") };

export function translate(language, key, vars = {}) {
  const entry = M[key];
  if (!entry) return key;
  let v = entry[language === "pl" ? 1 : 0];
  if (typeof v === "object") v = v[rules[language === "pl" ? "pl" : "en"].select(Number(vars.n))] ?? v.other;
  return v.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

// Notification text. Lock-screen privacy: no medication details unless enabled.
export function reminderText(settings, course, dose) {
  const l = settings.language;
  return {
    title: translate(l, "reminder.title"),
    body: settings.notificationDetails
      ? translate(l, "reminder.detailed", { time: dose.time, name: course.name, dose: course.dose })
      : translate(l, "reminder.generic"),
  };
}
